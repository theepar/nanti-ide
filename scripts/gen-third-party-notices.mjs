import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1"], { maxBuffer: 256 * 1024 * 1024 }).toString(),
);
const workspace = new Set(meta.workspace_members);
const rows = meta.packages
  .filter((p) => !workspace.has(p.id) && p.source)
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? "UNKNOWN (check the crate)",
    repo: p.repository ?? p.homepage ?? "",
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const ALLOWED = new Set([
  "MIT", "MIT-0", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0",
  "Unicode-DFS-2016", "Unlicense", "CC0-1.0", "0BSD", "BSL-1.0", "NCSA", "MPL-2.0",
]);

function permitted(expr) {
  const tokens = expr.replace(/\//g, " OR ").replace(/([()])/g, " $1 ").split(/\s+/).filter(Boolean);
  let i = 0;
  const parseOr = () => {
    let ok = parseAnd();
    while (tokens[i] === "OR") { i++; const r = parseAnd(); ok = ok || r; }
    return ok;
  };
  const parseAnd = () => {
    let ok = parseAtom();
    while (tokens[i] === "AND") { i++; const r = parseAtom(); ok = ok && r; }
    return ok;
  };
  const parseAtom = () => {
    if (tokens[i] === "(") { i++; const r = parseOr(); i++; return r; }
    const id = tokens[i++];
    if (tokens[i] === "WITH") i += 2; // "Apache-2.0 WITH LLVM-exception": an exception only widens the grant
    return ALLOWED.has(id);
  };
  return parseOr();
}
const forbidden = rows.filter((r) => !permitted(r.license));
if (forbidden.length) {
  console.error("LICENSE NOT ALLOWED:", forbidden.map((r) => `${r.name} ${r.version} (${r.license})`).join("; "));
  process.exit(1);
}

const unknown = rows.filter((r) => r.license.startsWith("UNKNOWN"));
const byLicense = new Map();
for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);

let out = `# Third-party notices

nanti. is built on open-source software. Each component below is distributed under the license shown;
the full license text is in the component's own package (crates.io / source repository). This file is
generated by \`scripts/gen-third-party-notices.mjs\`; do not edit it by hand.

Notable components: GPUI (Apache-2.0, Zed Industries), alacritty_terminal (Apache-2.0, The Alacritty
Project), tree-sitter and its grammars (MIT), ropey (MIT), wry (MIT OR Apache-2.0, Tauri), regex (MIT OR Apache-2.0).
Crates that offer a choice of licenses (for example \`MIT OR Apache-2.0\`) are used under the permissive option.
MPL-2.0 components are used unmodified; their source is available from the repositories listed.

## Rust crates (${rows.length})

Licenses in use: ${[...byLicense].sort((a, b) => b[1] - a[1]).map(([l, n]) => `${l} (${n})`).join(", ")}

| Crate | Version | License | Source |
|---|---|---|---|
`;
for (const r of rows) out += `| ${r.name} | ${r.version} | ${r.license} | ${r.repo} |\n`;

const lock = "extension-host/package-lock.json";
if (existsSync(lock)) {
  const pkgs = Object.entries(JSON.parse(readFileSync(lock, "utf8")).packages ?? {}).filter(([k]) => k);
  out += `\n## Node packages (extension host, ${pkgs.length})\n\n| Package | Version | License |\n|---|---|---|\n`;
  for (const [k, v] of pkgs) out += `| ${k.replace(/^.*node_modules\//, "")} | ${v.version} | ${v.license ?? "UNKNOWN"} |\n`;
} else {
  out += "\n## Node packages\n\nThe extension host currently has no npm dependencies.\n";
}
writeFileSync("THIRD_PARTY_NOTICES.md", out);

// Never edit the copied texts; this script only reads the crates' own files.
if (process.argv.includes("--full")) {
  const { readdirSync } = await import("node:fs");
  const { dirname, join } = await import("node:path");
  const seen = new Map(); // text -> crates that carry exactly this text
  let missing = [];
  for (const p of meta.packages.filter((p) => !workspace.has(p.id) && p.source)) {
    const dir = dirname(p.manifest_path);
    const files = readdirSync(dir).filter((f) => /^(licen[sc]e|copying|notice|unlicense)/i.test(f));
    if (!files.length) missing.push(`${p.name} ${p.version}`);
    for (const f of files) {
      const text = readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim();
      const key = `${f.toUpperCase().startsWith("NOTICE") ? "NOTICE" : "LICENSE"}\0${text}`;
      (seen.get(key) ?? seen.set(key, []).get(key)).push(`${p.name} ${p.version}`);
    }
  }
  let full = "THIRD-PARTY LICENSE TEXTS (verbatim copies from each package; do not edit)\n";
  for (const [key, crates] of seen) {
    const [kind, text] = key.split("\0");
    full += `\n${"=".repeat(78)}\n${kind} text used by: ${crates.join(", ")}\n${"=".repeat(78)}\n${text}\n`;
  }
  writeFileSync("THIRD_PARTY_LICENSES.txt", full);
  console.log(`wrote THIRD_PARTY_LICENSES.txt: ${seen.size} distinct texts; crates without a license file: ${missing.length}`);
  if (missing.length) console.log("NO LICENSE FILE (license is declared in Cargo.toml only):", missing.join(", "));
}
console.log(`wrote THIRD_PARTY_NOTICES.md: ${rows.length} crates, ${unknown.length} with unknown license`);
if (unknown.length) console.log("CHECK:", unknown.map((r) => r.name).join(", "));
